const porId = new Map(modulos.map((m) => [m.id, m]))
export const modulo = (id: string) => porId.get(id)
export const moduloDeConcepto = (concepto: string) => modulos.find((m) => m.concepto === concepto)

export function buscarLeccion(id: string) {
  for (const m of modulos) {
    const i = m.lecciones.findIndex((l) => l.id === id)
    if (i >= 0) return { modulo: m, leccion: m.lecciones[i], indice: i }
  }
  return null
}

export const leccionesDisponibles = modulos.flatMap((m) => m.lecciones.filter((l) => !l.enProduccion).map((l) => ({ modulo: m, leccion: l })))
